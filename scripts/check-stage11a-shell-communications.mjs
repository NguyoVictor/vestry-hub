import fs from 'node:fs';
const read = (p) => fs.readFileSync(p, 'utf8');
const checks = [];
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) });
const onboarding = read('src/pages/Onboarding.tsx');
const modules = read('src/config/modules.ts');
const navbar = read('src/components/layout/TopNavbar.tsx');
const email = read('supabase/functions/send-communication/index.ts');
const sms = read('supabase/functions/africastalking-sms/index.ts');
const emailWorker = read('supabase/functions/process-email-queue/index.ts');
const smsWorker = read('supabase/functions/process-sms-queue/index.ts');
const push = read('supabase/functions/send-push-notification/index.ts');
const registerToken = read('supabase/functions/register-device-token/index.ts');
const fcmHook = read('src/hooks/useFcmToken.ts');
const sw = read('public/firebase-messaging-sw.js');
const broadcast = read('src/pages/communications/AdminBroadcast.tsx');
const migration = read('supabase/migrations/20261005165445_p1_stage11a_device_token_hardening.sql');
check('onboarding renders canonical admin services', onboarding.includes('ADMIN_MODULES') && onboarding.includes('Choose the services your church will use'));
check('onboarding always includes core members module', onboarding.includes('useState<string[]>(["members_groups"])'));
check('onboarding mapping accepts canonical module keys', modules.includes('canonicalKeys.has(need as AdminModuleKey)'));
check('navbar global search queries tenant-scoped entities', navbar.includes('queryKey: ["global-search"') && navbar.includes('<CommandItem'));
check('navbar notification writes are tenant and user scoped', navbar.includes('.eq("tenant_id", church.tenantId)') && navbar.includes('.eq("user_id", church.userId)'));
check('email enqueue authorizes tenant actor', email.includes('authorizeTenantActor') && email.includes('reserve_communication_credits'));
check('sms enqueue authorizes tenant actor', sms.includes('authorizeTenantActor') && sms.includes('reserve_communication_credits'));
check('email worker uses queued jobs', emailWorker.includes('communication_jobs') && emailWorker.includes('finalize_communication_job'));
check('sms worker uses queued jobs', smsWorker.includes('communication_jobs') && smsWorker.includes('finalize_communication_job'));
check('push sender authorizes tenant actor', push.includes('authorizeTenantActor(req, supabase, tenant_id)'));
check('push token registration validates admin or member session', registerToken.includes('member_sessions') && registerToken.includes('supabase.auth.getUser(jwt)'));
check('frontend registers tokens through server function', fcmHook.includes('functions.invoke("register-device-token"'));
check('broadcast targets member-id keyed push tokens', broadcast.includes('const pushRecipientIds = memberIds'));
check('push click destination is propagated', broadcast.includes('link: "/member/announcements"') && push.includes('fcm_options'));
check('service worker opens requested notification path', sw.includes('event.notification?.data?.link') && sw.includes('clients.openWindow(destination)'));
check('device token table is server-only', migration.includes('revoke all on table public.device_tokens from public, anon, authenticated'));
const failed = checks.filter(c => !c.ok);
for (const c of checks) console.log(`${c.ok ? 'PASS' : 'FAIL'} ${c.name}`);
if (failed.length) { console.error(`Stage 11A contract: FAIL (${checks.length - failed.length}/${checks.length})`); process.exit(1); }
console.log(`Stage 11A contract: PASS (${checks.length}/${checks.length})`);
